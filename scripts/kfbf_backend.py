#!/usr/bin/env python3
"""Strict independent-channel KFBF -> standard TCZYX OME-Zarr.

Only source types established by the strict reader are accepted. Base pixels are
never rescaled, normalized or color converted. Display pyramids are generated by
explicit nearest-neighbor decimation from the preceding exact level. Native
lower levels remain in the original source and are not substituted for this data.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import time
import xml.etree.ElementTree as ET

import numpy as np

NS = 'http://www.openmicroscopy.org/Schemas/OME/2016-06'
CHUNK = 256


class KFBFBackendError(ValueError):
    def __init__(self, message, code='KFBF_BACKEND'):
        super().__init__(message)
        self.code = code
        self.details = {}


def require(condition, message, code='KFBF_BACKEND'):
    if not condition:
        raise KFBFBackendError(message, code)


def _reader(path):
    from kfbf_reader import KFBFReader
    return KFBFReader(path)


def _save(path, value):
    path = Path(path)
    tmp = path.with_suffix(path.suffix + '.tmp')
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    tmp.replace(path)


def _color(value):
    if value is None:
        return None
    require(isinstance(value, (list, tuple)) and len(value) == 3 and
            all(isinstance(v, int) and 0 <= v <= 255 for v in value),
            'Invalid source channel color', 'KFBF_METADATA')
    integer = (value[0] << 24) | (value[1] << 16) | (value[2] << 8) | 255
    return integer if integer < 2**31 else integer - 2**32


def _pyramid_dimensions(width, height):
    result = [(width, height)]
    while max(width, height) > 1024 and min(width, height) > 1:
        width, height = (width+1)//2, (height+1)//2
        result.append((width, height))
    return result


def _xml(meta):
    ET.register_namespace('', NS)
    tag = lambda name: '{'+NS+'}'+name
    root = ET.Element(tag('OME'), Creator='qupath-slide-converter; synthesized strict KFBF metadata')
    image = ET.SubElement(root, tag('Image'), ID='Image:0', Name=meta['name'])
    ET.SubElement(image, tag('Description')).text = (
        'OME metadata synthesized from the strict KFBF reader; original binary metadata remains in source.json. '
        'No intensity normalization, RGB conversion or inferred biological channel labels.')
    attrs = dict(ID='Pixels:0', DimensionOrder='XYZCT', Type=meta['dtype'],
                 SizeX=str(meta['X']), SizeY=str(meta['Y']), SizeC=str(meta['C']),
                 SizeZ='1', SizeT='1', Interleaved='false', BigEndian='false',
                 SignificantBits=str(meta['kfbf']['source_encoded_bit_depth']))
    for axis in ['X', 'Y']:
        value = meta['physical_size_'+axis.lower()]
        if value is not None:
            attrs['PhysicalSize'+axis] = repr(value)
            attrs['PhysicalSize'+axis+'Unit'] = 'µm'
    pixels = ET.SubElement(image, tag('Pixels'), **attrs)
    for c, channel in enumerate(meta['kfbf']['channels']):
        attrs = dict(ID='Channel:0:'+str(c), SamplesPerPixel='1')
        if channel.get('name') is not None:
            attrs['Name'] = channel['name']
        color = _color(channel.get('color_rgb'))
        if color is not None:
            attrs['Color'] = str(color)
        ET.SubElement(pixels, tag('Channel'), **attrs)
    ET.SubElement(pixels, tag('MetadataOnly'))
    # Exposure has no proven unit in the current binary contract. Preserve raw
    # values in the sidecar; do not fabricate ExposureTimeUnit="ms".
    return ET.tostring(root, encoding='unicode')


def _coverage_summary(coverage, width, height, channels):
    """Separate per-channel sample counts from the spatial union of missing areas."""
    base = [v for v in coverage.get('levels', []) if v['level'] == 0]
    rectangles = [r for v in base for r in v.get('missing_rectangles', [])]
    events = {}
    for index, rect in enumerate(rectangles):
        x, y, w, h = (rect[k] for k in ('x', 'y', 'width', 'height'))
        events.setdefault(y, []).append((1, index, x, x+w))
        events.setdefault(y+h, []).append((-1, index, x, x+w))
    active, previous, union_area = {}, 0, 0
    for y in sorted(events):
        end, length = 0, 0
        for start, stop in sorted(active.values()):
            if stop > end:
                length += stop-max(start, end)
                end = stop
        union_area += length*(y-previous)
        for action, index, start, stop in events[y]:
            if action == 1: active[index] = (start, stop)
            else: active.pop(index)
        previous = y
    missing = sum(v.get('missing_pixels', 0) for v in base)
    require(missing == coverage.get('base_missing_pixels', missing), 'Missing sample accounting differs', 'KFBF_COVERAGE')
    return dict(base_missing_channel_samples=missing, base_recorded_channel_samples=width*height*channels-missing,
                base_total_channel_samples=width*height*channels,
                base_missing_spatial_union_pixels=union_area, base_total_spatial_pixels=width*height,
                per_channel=[dict(channel=v['channel'], missing_pixels=v.get('missing_pixels', 0),
                                  missing_rectangles=v.get('missing_rectangles', [])) for v in base],
                units='channel-samples count each channel separately; spatial union counts an XY location once')


def _metadata(path, source, missing_policy="error"):
    width, height = int(source.width), int(source.height)
    count = int(source.channel_count)
    require(width > 0 and height > 0 and 0 < count <= 256, 'Invalid KFBF dimensions/channels', 'KFBF_METADATA')
    dtype = np.dtype(source.dtype)
    precision = int(source.source_encoded_bit_depth)
    require(dtype.name in ('uint8', 'uint16'), 'Unsupported decoded source type', 'KFBF_PIXEL_TYPE')
    require(0 < precision <= dtype.itemsize*8 and
            (dtype.name == 'uint8') == (precision <= 8),
            'Encoded precision and decoded storage type disagree; no bit-depth conversion is permitted', 'KFBF_PIXEL_TYPE')
    channels = [dict(value) for value in source.channels]
    require(len(channels) == count, 'Source channel table count differs from pixel channels', 'KFBF_METADATA')
    for channel in channels:
        name = channel.get('name')
        require(name is None or isinstance(name, str), 'Channel name must be an original string or unknown', 'KFBF_METADATA')
        if name == '': channel['name'] = None
        _color(channel.get('color_rgb'))
    mpp = source.mpp
    require(mpp is None or (isinstance(mpp, (int, float)) and math.isfinite(mpp) and mpp > 0),
            'Invalid source physical calibration', 'KFBF_METADATA')
    if mpp is not None: mpp = float(mpp)
    audit = source.metadata()
    require(isinstance(audit, dict), 'Reader metadata must be an object', 'KFBF_METADATA')
    levels = _pyramid_dimensions(width, height)
    stat = path.stat()
    image = dict(series=0, name='KFBF primary image', X=width, Y=height, C=count, Z=1, T=1, rgb=False)
    details = dict(reader_audit=audit, channels=channels, source_encoded_bit_depth=precision,
                   decoded_dtype=dtype.name, decoder_conversion='none',
                   missing_pixels_policy=missing_policy, source_coverage=source.coverage_report,
                   coverage_summary=_coverage_summary(source.coverage_report, width, height, count),
                   output_levels=[dict(level=i, width=w, height=h, downsample=2**i) for i, (w, h) in enumerate(levels)],
                   pyramid_policy='Exact base retained. Display levels regenerated with a[::2,::2] from preceding level; native lower levels not exported.',
                   channel_metadata_provenance='Original strict-reader fields; unknown names/colors are omitted from OME XML.',
                   exposure_policy='Raw source values retained in sidecar only; physical unit not asserted.')
    result = dict(image, dtype=dtype.name, effective_channels=count, rgb_samples=1,
                  format='KFBF independent channels (strict native reader)', resolution_count=len(levels),
                  interleaved=False, little_endian=True, channels=[v.get('name') for v in channels],
                  physical_size_x=mpp, physical_size_y=mpp, physical_size_unit='µm',
                  series_inventory=[image], inventory=[dict(path=str(path), size=stat.st_size, mtime_ns=stat.st_mtime_ns)],
                  classification='independent_channels', kfbf=details,
                  source_xml_provenance='synthesized_from_strict_kfbf_metadata', icc_status='not_applicable_to_independent_intensity_channels')
    result['source_xml'] = _xml(result)
    return result


def inspect_kfbf(path, cfg=None, series=None):
    require(series in (None, 0), 'KFBF exposes only the full-resolution primary series', 'INVALID_SERIES')
    path = Path(path).resolve()
    with _reader(path) as source:
        return _metadata(path, source, (cfg or {}).get("kfbf_missing_pixels", "error"))


def validate_kfbf(meta, missing_policy=None):
    require(not meta['rgb'] and meta['effective_channels'] == meta['C'] and meta['Z'] == meta['T'] == 1,
            'KFBF requires independent 2D intensity channels', 'KFBF_CHANNEL_LAYOUT')
    require(meta['dtype'] in ('uint8', 'uint16'), 'Unsupported KFBF decoded type', 'KFBF_PIXEL_TYPE')
    policy = meta['kfbf']['missing_pixels_policy']
    require(missing_policy is None or missing_policy == policy, 'Selected missing-pixel policy differs from inspection', 'KFBF_POLICY')
    require(policy in ('error', 'black'), 'Unknown missing-pixels policy', 'KFBF_POLICY')
    coverage = meta['kfbf']['source_coverage']
    if coverage.get('base_missing_pixels', 0) and policy == 'error':
        error = KFBFBackendError('KFBF source coverage is incomplete. An explicit user choice is required to represent missing pixels with black; unknown content is not recovered.', 'KFBF_MISSING_PIXELS')
        error.details = dict(coverage=coverage)
        raise error
    for level in coverage.get('levels', []):
        require(not level.get('overlap_pixels') and not level.get('out_of_bounds_pixels'), 'KFBF has ambiguous overlap or out-of-bounds coordinates', 'KFBF_GEOMETRY')
    return meta['kfbf']


def _match(path, source, meta):
    fresh = _metadata(Path(path).resolve(), source, meta["kfbf"]["missing_pixels_policy"])
    validate_kfbf(fresh)
    wanted = {k: v for k, v in meta.items() if k != 'source_xml'}
    observed = {k: v for k, v in fresh.items() if k != 'source_xml'}
    require(wanted == observed, 'KFBF source or parsed metadata changed since inspection', 'KFBF_SOURCE_CHANGED')
    return fresh


def _region(source, channel, x, y, width, height, missing_policy="error"):
    pixels = source.read_region(0, channel, x, y, width, height, missing_pixels=missing_policy)
    require(isinstance(pixels, np.ndarray) and pixels.shape == (height, width) and
            pixels.dtype == np.dtype(source.dtype),
            'Decoded source region has unexpected shape or dtype', 'KFBF_DECODE_CONTRACT')
    return pixels


class RegionReader:
    """The small Bio-Formats-style API consumed by slide_probe.read_rois."""
    def __init__(self, path, missing_policy="error"):
        self.source = _reader(path)
        self.missing_policy = missing_policy
    def setSeries(self, series):
        require(series == 0, 'Only KFBF series 0 is supported', 'INVALID_SERIES')
    def setResolution(self, level):
        require(level == 0, 'Source ROI validation requires the KFBF base level', 'KFBF_RESOLUTION')
    def isInterleaved(self):
        return False
    def getIndex(self, z, c, t):
        require(z == t == 0 and 0 <= c < self.source.channel_count, 'Invalid KFBF plane', 'KFBF_CHANNEL_LAYOUT')
        return c
    def openBytes(self, plane, x, y, width, height):
        pixels = _region(self.source, plane, x, y, width, height, self.missing_policy)
        return np.asarray(pixels, dtype=np.dtype(self.source.dtype).newbyteorder('<')).tobytes(order='C')
    def close(self):
        self.source.close()


def open_reader(path, cfg=None):
    return RegionReader(path, (cfg or {}).get("kfbf_missing_pixels", "error"))


def _blocks(width, height, size=CHUNK):
    for y in range(0, height, size):
        for x in range(0, width, size):
            yield x, y, min(size, width-x), min(size, height-y)


def _zarr(path, meta):
    import zarr
    root = zarr.open_group(str(path), mode='r')
    require(root.attrs.get('bioformats2raw.layout') == 3, 'Invalid Zarr layout marker', 'KFBF_ZARR_STRUCTURE')
    group = root['0']
    scales = group.attrs.get('multiscales', [])
    require(len(scales) == 1 and [a['name'] for a in scales[0]['axes']] == list('tczyx'),
            'Expected one TCZYX multiscale group', 'KFBF_ZARR_STRUCTURE')
    levels = meta['kfbf']['output_levels']
    require([v['path'] for v in scales[0]['datasets']] == [str(i) for i in range(len(levels))],
            'Unexpected Zarr levels/order', 'KFBF_ZARR_STRUCTURE')
    for value in levels:
        ar = group[str(value['level'])]
        require(tuple(ar.shape) == (1, meta['C'], 1, value['height'], value['width']) and ar.dtype == np.dtype(meta['dtype']),
                'Zarr dimensions/channel count/type changed', 'KFBF_ZARR_STRUCTURE')
    return root, group


def write_kfbf_zarr(path, meta, output, report_path, workers=4):
    import zarr
    from numcodecs import Blosc
    path, output = Path(path).resolve(), Path(output)
    require(workers > 0, 'Worker count must be positive', 'BAD_PARAMETERS')
    require(not output.exists(), 'KFBF Zarr output already exists', 'OUTPUT_EXISTS')
    started = time.monotonic()
    with _reader(path) as source:
        _match(path, source, meta)
        output.mkdir(parents=True, exist_ok=False)
        root = zarr.open_group(str(output), mode='w', zarr_format=2)
        root.attrs['bioformats2raw.layout'] = 3
        group = root.create_group('0')
        ome = root.create_group('OME'); ome.attrs['series'] = ['0']
        (output/'OME'/'METADATA.ome.xml').write_text(meta.get('source_xml') or _xml(meta), encoding='utf-8')
        axes = [dict(name=a, type='time' if a == 't' else 'channel' if a == 'c' else 'space') for a in 'tczyx']
        if meta['physical_size_x'] is not None:
            axes[-1]['unit'] = axes[-2]['unit'] = 'micrometer'
        datasets = []
        for level in meta['kfbf']['output_levels']:
            ds = level['downsample']
            xscale = ds * (meta['physical_size_x'] or 1)
            yscale = ds * (meta['physical_size_y'] or 1)
            datasets.append(dict(path=str(level['level']), coordinateTransformations=[dict(type='scale', scale=[1, 1, 1, yscale, xscale])]))
        group.attrs['multiscales'] = [dict(version='0.4', name=meta['name'], axes=axes, datasets=datasets,
                                          metadata=dict(method='nearest-neighbor [::2,::2] from previous level; exact base unchanged'))]
        completed = []
        for level in meta['kfbf']['output_levels']:
            n, width, height = level['level'], level['width'], level['height']
            ar = group.create_array(str(n), shape=(1, meta['C'], 1, height, width),
                                    chunks=(1, 1, 1, min(CHUNK, height), min(CHUNK, width)),
                                    dtype=np.dtype(meta['dtype']).newbyteorder('<'),
                                    compressor=Blosc(cname='lz4', clevel=5, shuffle=Blosc.SHUFFLE),
                                    fill_value=0, chunk_key_encoding={'name': 'v2', 'configuration': {'separator': '/'}})
            written = 0
            for c in range(meta['C']):
                for x, y, w, h in _blocks(width, height):
                    if n == 0:
                        data = _region(source, c, x, y, w, h, meta["kfbf"]["missing_pixels_policy"])
                    else:
                        previous = group[str(n-1)]
                        data = np.asarray(previous[0, c, 0, 2*y:min(2*(y+h), previous.shape[-2]):2,
                                                               2*x:min(2*(x+w), previous.shape[-1]):2])
                    require(data.shape == (h, w) and data.dtype == np.dtype(meta['dtype']),
                            'Pyramid tile shape/type differs', 'KFBF_PYRAMID')
                    ar[0, c, 0, y:y+h, x:x+w] = data
                    written += w*h
                print('KFBF_ZARR level=%d channel=%d/%d complete' % (n, c+1, meta['C']), flush=True)
            completed.append(dict(level=n, width=width, height=height, channels=meta['C'], values_written=written))
        # The source object and independent saved metadata must still agree.
        _match(path, source, meta)
    report = dict(status='WRITTEN_PENDING_PIXEL_VALIDATION', levels=completed,
                  source_backend='bundled_strict_kfbf', dtype=meta['dtype'], channels=meta['C'],
                  source_encoded_bit_depth=meta['kfbf']['source_encoded_bit_depth'],
                  pyramid_policy=meta['kfbf']['pyramid_policy'], missing_pixels_policy=meta['kfbf']['missing_pixels_policy'],
                  source_coverage=meta['kfbf']['source_coverage'], coverage_summary=meta['kfbf']['coverage_summary'],
                  missing_content='Absent original pixels remain unknown; explicit black is a display value, not reconstructed data.',
                  requested_workers=workers, io_strategy='bounded serial source reads; no shared file cursor across threads',
                  elapsed_seconds=time.monotonic()-started)
    _save(report_path, report)
    return report


def verify_kfbf_zarr(path, meta, zarr_path):
    _, group = _zarr(zarr_path, meta)
    reports = []
    with _reader(path) as source:
        _match(path, source, meta)
        for level in meta['kfbf']['output_levels']:
            n, width, height = level['level'], level['width'], level['height']
            ar = group[str(n)]
            channels = []
            for c in range(meta['C']):
                digest = hashlib.sha256(); count = 0
                for x, y, w, h in _blocks(width, height, 512):
                    if n == 0:
                        expected = _region(source, c, x, y, w, h, meta["kfbf"]["missing_pixels_policy"])
                    else:
                        previous = group[str(n-1)]
                        expected = np.asarray(previous[0, c, 0, 2*y:min(2*(y+h), previous.shape[-2]):2,
                                                               2*x:min(2*(x+w), previous.shape[-1]):2])
                    actual = np.asarray(ar[0, c, 0, y:y+h, x:x+w])
                    require(expected.dtype == actual.dtype and np.array_equal(expected, actual),
                            'Source/display pyramid differs from Zarr at level %d channel %d x %d y %d' % (n, c, x, y),
                            'KFBF_ZARR_PIXEL_MISMATCH')
                    digest.update(np.asarray(actual, dtype=np.dtype(meta['dtype']).newbyteorder('<')).tobytes())
                    count += actual.size
                channels.append(dict(channel=c, values_compared=count, block_order_sha256=digest.hexdigest()))
                print('KFBF_ZARR_VERIFIED level=%d channel=%d/%d' % (n, c+1, meta['C']), flush=True)
            reports.append(dict(level=n, width=width, height=height, channels=channels))
        _match(path, source, meta)
    return dict(status='PASS', verification='every recorded source base sample plus explicitly represented missing areas; each generated display pixel',
                missing_pixels_policy=meta['kfbf']['missing_pixels_policy'], coverage_summary=meta['kfbf']['coverage_summary'],
                unknown_content_recovered=False,
                block_order='channel, y-major then x-major 512x512 blocks; pixels within blocks row-major little-endian', levels=reports,
                total_values_compared=sum(c['values_compared'] for l in reports for c in l['channels']))


def verify_kfbf_ome(zarr_path, meta, tiff_path):
    import tifffile
    import zarr
    _, group = _zarr(zarr_path, meta)
    reports = []
    with tifffile.TiffFile(tiff_path) as tf:
        require(tf.ome_metadata and len(tf.series) == 1, 'Expected one OME-TIFF primary series', 'KFBF_TIFF_STRUCTURE')
        series = tf.series[0]
        require(len(series.levels) == len(meta['kfbf']['output_levels']), 'OME-TIFF pyramid count changed', 'KFBF_TIFF_STRUCTURE')
        for n, level in enumerate(series.levels):
            shape = dict(zip(level.axes, level.shape))
            wanted = meta['kfbf']['output_levels'][n]
            require(set(level.axes) <= set('TCZYX') and shape.get('C', 1) == meta['C'] and
                    shape['Y'] == wanted['height'] and shape['X'] == wanted['width'] and
                    shape.get('T', 1) == shape.get('Z', 1) == 1 and level.dtype == np.dtype(meta['dtype']),
                    'OME-TIFF layout/type changed', 'KFBF_TIFF_STRUCTURE')
            require(all(int(page.compression) == 5 for page in level.pages), 'OME-TIFF must use lossless LZW on every plane', 'KFBF_TIFF_STRUCTURE')
            store = level.aszarr()
            try:
                ar = zarr.open(store, mode='r')
                if isinstance(ar, zarr.Group): ar = ar[str(n)]
                channels = []
                for c in range(meta['C']):
                    digest = hashlib.sha256(); count = 0
                    for x, y, w, h in _blocks(wanted['width'], wanted['height'], 512):
                        selections = dict(T=0, C=c, Z=0, Y=slice(y, y+h), X=slice(x, x+w))
                        actual = np.asarray(ar[tuple(selections[a] for a in level.axes)])
                        expected = np.asarray(group[str(n)][0, c, 0, y:y+h, x:x+w])
                        require(actual.shape == (h, w) and actual.dtype == expected.dtype and np.array_equal(actual, expected),
                                'OME-TIFF differs at level %d channel %d x %d y %d' % (n, c, x, y), 'KFBF_TIFF_PIXEL_MISMATCH')
                        digest.update(np.asarray(actual, dtype=np.dtype(meta['dtype']).newbyteorder('<')).tobytes()); count += actual.size
                    channels.append(dict(channel=c, values_compared=count, block_order_sha256=digest.hexdigest()))
                    print('KFBF_OME_VERIFIED level=%d channel=%d/%d' % (n, c+1, meta['C']), flush=True)
                reports.append(dict(level=n, width=wanted['width'], height=wanted['height'], channels=channels))
            finally:
                store.close()
    return dict(status='PASS', verification='every verified Zarr pixel versus OME-TIFF, every independent channel and display level',
                levels=reports, total_values_compared=sum(c['values_compared'] for l in reports for c in l['channels']))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('input', 'metadata', 'output', 'report'): parser.add_argument('--'+name, required=True)
    parser.add_argument('--workers', type=int, default=4)
    parser.add_argument("--missing-pixels", choices=["error", "black"], default="error")
    args = parser.parse_args()
    try:
        metadata = json.loads(Path(args.metadata).read_text(encoding='utf-8'))
        require(metadata['kfbf']['missing_pixels_policy'] == args.missing_pixels, 'Command and inspected missing-pixel policies differ', 'KFBF_POLICY')
        report = write_kfbf_zarr(args.input, metadata, args.output, args.report, args.workers)
        print(json.dumps(report, ensure_ascii=False))
        return 0
    except Exception as exc:
        print(json.dumps(dict(status=getattr(exc, 'code', 'FAILED'), message=str(exc)), ensure_ascii=False))
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
